"""Encode or decode an updater.sh for the Sharp Zaurus ROM updater.

The updater that the Sharp boot loader starts (hold OK and press On/Off)
only runs an updater.sh in its own encoding: every byte of the shell script
replaced through a fixed substitution. Output and input have the same
length.

The table covers the characters of a plain ASCII shell script except tab,
'@', 'Q' and '~'. A script holding any other byte is refused rather than
encoded into something the updater would misread.
"""

import argparse
import sys

# Plain byte -> encoded byte
# fmt: off
ENCODE = {
    0x0a: 0x2f, 0x20: 0x41, 0x21: 0x22, 0x22: 0x13, 0x23: 0x24, 0x24: 0xa1,
    0x25: 0x38, 0x26: 0x27, 0x27: 0x44, 0x28: 0x19, 0x29: 0x34, 0x2a: 0x81,
    0x2b: 0x36, 0x2c: 0xed, 0x2d: 0x2e, 0x2e: 0x0b, 0x2f: 0xc7, 0x30: 0xac,
    0x31: 0xc9, 0x32: 0x23, 0x33: 0x2a, 0x34: 0x35, 0x35: 0x2c, 0x36: 0xb6,
    0x37: 0x6c, 0x38: 0x79, 0x39: 0xee, 0x3a: 0x71, 0x3b: 0x6d, 0x3c: 0xd1,
    0x3d: 0x48, 0x3e: 0x3b, 0x3f: 0xe2, 0x41: 0x42, 0x42: 0x37, 0x43: 0xcd,
    0x44: 0xd0, 0x45: 0x90, 0x46: 0xa5, 0x47: 0x88, 0x48: 0x85, 0x49: 0x7c,
    0x4a: 0x00, 0x4b: 0xcb, 0x4c: 0x4d, 0x4d: 0x4e, 0x4e: 0x82, 0x4f: 0xfb,
    0x50: 0x80, 0x52: 0x97, 0x53: 0xb9, 0x54: 0xdd, 0x55: 0x56, 0x56: 0x93,
    0x57: 0x7a, 0x58: 0x61, 0x59: 0x5a, 0x5a: 0x5b, 0x5b: 0x5c, 0x5c: 0xf8,
    0x5d: 0x5e, 0x5e: 0xf9, 0x5f: 0x28, 0x60: 0xf0, 0x61: 0xe9, 0x62: 0x03,
    0x63: 0xb0, 0x64: 0x60, 0x65: 0xec, 0x66: 0x39, 0x67: 0xca, 0x68: 0x73,
    0x69: 0xa8, 0x6a: 0x6b, 0x6b: 0x12, 0x6c: 0x31, 0x6d: 0xe4, 0x6e: 0x30,
    0x6f: 0x25, 0x70: 0xe7, 0x71: 0xc0, 0x72: 0x9d, 0x73: 0x6e, 0x74: 0x3e,
    0x75: 0x50, 0x76: 0x77, 0x77: 0x02, 0x78: 0xbd, 0x79: 0x58, 0x7a: 0x7f,
    0x7b: 0xd8, 0x7c: 0x0f, 0x7d: 0x9c,
}
# fmt: on

DECODE = {v: k for k, v in ENCODE.items()}


def translate(data: bytes, table: dict[int, int], what: str) -> bytes:
    out = bytearray()

    for offset, byte in enumerate(data):
        if byte not in table:
            line = data.count(b'\n', 0, offset) + 1 if what == 'encode' else None
            where = f'line {line}' if line is not None else f'offset {offset}'
            raise ValueError(f'cannot {what} byte 0x{byte:02x} at {where}')
        out.append(table[byte])

    return bytes(out)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
        allow_abbrev=False,
    )
    parser.add_argument(
        '-d', '--decode', action='store_true', help='decode an encoded updater.sh instead'
    )
    parser.add_argument('input', help='script to read')
    parser.add_argument('output', help='file to write')
    args = parser.parse_args()

    with open(args.input, 'rb') as f:
        data = f.read()

    try:
        if args.decode:
            result = translate(data, DECODE, 'decode')
        else:
            result = translate(data, ENCODE, 'encode')
    except ValueError as e:
        print(f'{args.input}: {e}', file=sys.stderr)
        return 1

    with open(args.output, 'wb') as f:
        f.write(result)

    return 0


if __name__ == '__main__':
    sys.exit(main())
